"""SYNTHETIC electrochemical data with known parameters (tests and the labelled demo workspace only).

Files are written in several realistic export layouts (CSV, Gamry-style TSV with a units row,
semicolon/decimal-comma EC-Lab-style) to exercise the parser. Every file starts with a
'DEMO - SYNTHETIC DATA' banner line.
"""
from __future__ import annotations

import numpy as np

BANNER = "DEMO - SYNTHETIC DATA - generated by WETCOR AI, not a laboratory measurement"


def butler_volmer(e, e_corr: float, icorr: float, beta_a: float, beta_c: float):
    """i = i_corr [10^((E-Ecorr)/beta_a) - 10^(-(E-Ecorr)/beta_c)]  (beta in V/decade)."""
    eta = np.asarray(e, dtype=float) - e_corr
    return icorr * (10 ** (eta / beta_a) - 10 ** (-eta / beta_c))


def pdp_tsv(e_corr=-0.65, icorr=5e-6, beta_a=0.06, beta_c=0.12, area_cm2=1.0, span=0.3, step=0.001, noise=0.01, seed=0) -> bytes:
    rng = np.random.default_rng(seed)
    e = np.arange(e_corr - span, e_corr + span + step / 2, step)
    i = butler_volmer(e, e_corr, icorr, beta_a, beta_c) * (1 + rng.normal(0, noise, e.size)) * area_cm2
    lines = ["EXPLAIN", "TAG\tPOTENTIODYNAMIC", f"NOTES\t{BANNER}", f"AREA\t{area_cm2}\tcm^2", "CURVE\tTABLE\t" + str(e.size),
             "\tPt\tT\tVf\tIm", "\t#\ts\tV vs. Ref.\tA"]
    lines += [f"\t{k}\t{k * step / 0.001:.3f}\t{ev:.6f}\t{iv:.6e}" for k, (ev, iv) in enumerate(zip(e, i))]
    return ("\n".join(lines) + "\n").encode()


def lpr_csv(e_corr=-0.65, icorr=5e-6, beta_a=0.06, beta_c=0.12, area_cm2=1.0, half=0.015, step=0.0002, noise=0.002, seed=1) -> bytes:
    rng = np.random.default_rng(seed)
    e = np.arange(e_corr - half, e_corr + half + step / 2, step)
    i = butler_volmer(e, e_corr, icorr, beta_a, beta_c) * area_cm2 + rng.normal(0, noise * icorr * area_cm2, e.size)
    rows = [f"# {BANNER}", "E (mV),I (uA)"] + [f"{ev * 1000:.3f},{iv * 1e6:.6f}" for ev, iv in zip(e, i)]
    return ("\n".join(rows) + "\n").encode()


def ocp_csv(e0=-0.55, e_inf=-0.65, tau=300.0, duration=1800, dt=2.0, noise=0.4e-3, seed=2, reference="SCE") -> bytes:
    rng = np.random.default_rng(seed)
    t = np.arange(0, duration + dt / 2, dt)
    e = e_inf + (e0 - e_inf) * np.exp(-t / tau) + rng.normal(0, noise, t.size)
    rows = [f"# {BANNER}", f"Reference electrode: {reference}", f"Time (s),Potential (V vs {reference})"] + [f"{a:.1f},{b:.6f}" for a, b in zip(t, e)]
    return ("\n".join(rows) + "\n").encode()


def randles_cpe(f, rs=15.0, rct=2500.0, q=4e-5, n=0.9):
    w = 2 * np.pi * np.asarray(f, dtype=float)
    return rs + rct / (1 + rct * q * (1j * w) ** n)


def eis_semicolon(rs=15.0, rct=2500.0, q=4e-5, n=0.9, noise=0.005, seed=3) -> bytes:
    rng = np.random.default_rng(seed)
    f = np.logspace(5, -2, 57)
    z = randles_cpe(f, rs, rct, q, n) * (1 + rng.normal(0, noise, f.size))
    phase = np.degrees(np.angle(z))

    def dc(x: float) -> str:
        return f"{x:.6g}".replace(".", ",")
    rows = [f"# {BANNER}", "freq/Hz;Re(Z)/Ohm;-Im(Z)/Ohm;|Z|/Ohm;Phase(Z)/deg"]
    rows += [";".join(dc(v) for v in (fv, zv.real, -zv.imag, abs(zv), pv)) for fv, zv, pv in zip(f, z, phase)]
    return ("\n".join(rows) + "\n").encode()
