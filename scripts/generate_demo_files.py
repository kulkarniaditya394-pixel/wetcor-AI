"""Write SYNTHETIC demo files to data/demo/ for trying the import wizard and image upload by hand.

Usage (from the wetcor-ai folder):  backend\\.venv\\Scripts\\python scripts\\generate_demo_files.py
Every file name starts with DEMO_SYNTHETIC_ and every text file starts with a DEMO banner line.
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))

from app.services.electrochemistry import synthetic as ES  # noqa: E402
from app.services.wettability.synthetic import encode_png, synthetic_drop  # noqa: E402


def main() -> None:
    out = ROOT / "data" / "demo"
    out.mkdir(parents=True, exist_ok=True)
    files = {
        "DEMO_SYNTHETIC_ocp.csv": ES.ocp_csv(),
        "DEMO_SYNTHETIC_lpr_mV_uA.csv": ES.lpr_csv(),
        "DEMO_SYNTHETIC_polarisation_gamry_style.txt": ES.pdp_tsv(),
        "DEMO_SYNTHETIC_eis_semicolon_decimal_comma.csv": ES.eis_semicolon(),
    }
    for theta, kw, name in [(65, {}, "DEMO_SYNTHETIC_droplet_65deg.png"), (112, {}, "DEMO_SYNTHETIC_droplet_112deg.png"),
                            (80, {"tilt_deg": 5}, "DEMO_SYNTHETIC_droplet_80deg_tilted5.png"),
                            (70, {"background": 125, "foreground": 104}, "DEMO_SYNTHETIC_droplet_70deg_low_contrast.png")]:
        img, _ = synthetic_drop(theta, size=(960, 640), radius_px=200, baseline_y=470, **kw)
        files[name] = encode_png(img)
    for name, data in files.items():
        (out / name).write_bytes(data)
        print(f"wrote data/demo/{name}")
    (out / "README.txt").write_text(
        "DEMO - SYNTHETIC DATA\n\nThese files are generated by scripts/generate_demo_files.py with known parameters "
        "(contact angles 65/112/80/70 deg; i_corr 5 uA/cm2, beta_a 60 mV/dec, beta_c 120 mV/dec, E_corr -0.65 V; "
        "Randles-CPE EIS). They exist to test the software and are not laboratory measurements.\n", encoding="utf-8")


if __name__ == "__main__":
    main()
