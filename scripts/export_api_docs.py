"""Generate docs/openapi.json and docs/API.md from the implemented FastAPI routes."""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))

from app.main import app  # noqa: E402


def main() -> None:
    spec = app.openapi()
    (ROOT / "docs" / "openapi.json").write_text(json.dumps(spec, indent=2), encoding="utf-8")
    lines = ["# WETCOR AI REST API", "", "Generated by `scripts/export_api_docs.py` from the running code "
             f"(API version {spec['info']['version']}). Interactive docs: `http://127.0.0.1:8100/docs` while the backend runs.", "",
             "All endpoints are served on the loopback interface only. Errors are JSON `{\"detail\": ...}` with meaningful status codes "
             "(404 missing record, 409 conflict/integrity, 413 too large, 415 wrong file type, 422 validation or scientifically refused request).", ""]
    groups: dict[str, list[str]] = {}
    for path, ops in spec["paths"].items():
        for method, op in ops.items():
            tag = (op.get("tags") or ["other"])[0]
            params = ", ".join(f"`{p['name']}`" + ("*" if p.get("required") else "") for p in op.get("parameters", []))
            body = op.get("requestBody", {}).get("content", {})
            body_t = next(iter(body), "")
            ref = body.get(body_t, {}).get("schema", {}).get("$ref", "").split("/")[-1] if body_t else ""
            groups.setdefault(tag, []).append(f"| `{method.upper()}` | `{path}` | {op.get('summary', '')} | {params} | {ref or body_t} |")
    for tag, rows in groups.items():
        lines += [f"## {tag}", "", "| Method | Path | Summary | Parameters (* required) | Body |", "|---|---|---|---|---|", *rows, ""]
    lines += ["## Schemas", "", "See `docs/openapi.json` for the full request/response schemas (`components.schemas`).", ""]
    (ROOT / "docs" / "API.md").write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote docs/API.md ({sum(len(r) for r in groups.values())} operations) and docs/openapi.json")


if __name__ == "__main__":
    main()
